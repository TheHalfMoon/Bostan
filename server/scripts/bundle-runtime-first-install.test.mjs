import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, readdir, rm, writeFile, lstat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { commitCompiledRuntimeOutputs } from './bundle-runtime-commit.mjs';

const response = dir => ({ outputFiles: [
  { path: join(dir, 'index.mjs'), contents: Buffer.from('import "./server.mjs";') },
  { path: join(dir, 'server.mjs'), contents: Buffer.from('console.log(42);') },
] });

const notExists = async path => assert.equal(await lstat(path).then(() => true, e => {
  if (e.code === 'ENOENT') return false;
  throw e;
}), false);

// New-install marker failure must not strand an unowned runtime at the canonical path.
test('fresh build marker failure isolates exact generated bytes and permits retry', async () => {
  const root = await mkdtemp(join(tmpdir(), 'bostan-b129-owned-'));
  const dir = join(root, 'runtime');
  const entry = join(root, 'entry.js');
  const admission = async (_entry, outdir) => { assert.equal(outdir, dir); return dir; };
  try {
    await assert.rejects(commitCompiledRuntimeOutputs({
      entry, outdir: dir, result: response(dir), assertSafeRuntimeOutdir: admission,
      recordRuntimeOutputOwnership: async () => { throw new Error('synthetic disk marker write failure'); },
    }), /marker write failure/);
    await notExists(dir);
    const rejected = (await readdir(root)).filter(x => x.startsWith('.bostan-runtime-rejected-'));
    assert.equal(rejected.length, 1);
    assert.deepEqual((await readdir(join(root, rejected[0]))).sort(), ['index.mjs', 'server.mjs']);
    assert.equal(await readFile(join(root, rejected[0], 'server.mjs'), 'utf8'), 'console.log(42);');
    await commitCompiledRuntimeOutputs({
      entry, outdir: dir, result: response(dir), assertSafeRuntimeOutdir: admission,
      recordRuntimeOutputOwnership: async () => {},
    });
    assert.equal(await readFile(join(dir, 'server.mjs'), 'utf8'), 'console.log(42);');
  } finally { await rm(root, { recursive: true, force: true }); }
});

// Never move foreign data merely because a failing marker writer touched it.
test('fresh marker failure preserves foreign modified output in place', async () => {
  const root = await mkdtemp(join(tmpdir(), 'bostan-b129-owned-'));
  const dir = join(root, 'runtime');
  try {
    await assert.rejects(commitCompiledRuntimeOutputs({
      entry: join(root, 'entry.js'), outdir: dir, result: response(dir),
      assertSafeRuntimeOutdir: async () => dir,
      recordRuntimeOutputOwnership: async () => {
        await writeFile(join(dir, 'IMPORTANT_USER_DATA.txt'), 'DO NOT MOVE');
        throw new Error('synthetic marker failure');
      },
    }), /marker failure/);
    assert.equal(await readFile(join(dir, 'IMPORTANT_USER_DATA.txt'), 'utf8'), 'DO NOT MOVE');
  } finally { await rm(root, { recursive: true, force: true }); }
});
